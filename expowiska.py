"""Forum-Expowiska aus lokalem HTML importieren und reproduzierbar Karten/Rundgänge erzeugen.

python3 expowiska.py --html /pfad/forum.html   # normalisierte Quelle speichern
python3 expowiska.py                          # aus gespeicherter Quelle neu erzeugen
python3 expowiska.py --embed                  # zusätzlich Katalog im Userscript aktualisieren
Keine Netzwerkzugriffe. Karten-IDs stammen aus margobot_world.json.
"""
import argparse
from collections import deque
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import unicodedata

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'docs' / 'expowiska-source.json'
OUT = ROOT / 'margobot_expowiska.json'
URL = 'https://forum.margonem.pl/?task=forum&show=posts&id=514156'
BEGIN = '    // BEGIN FORUM EXPOWISKA (generated by expowiska.py)'
END = '    // END FORUM EXPOWISKA'
# Im Forenauszug abweichend geschriebene Namen; keine automatische Fuzzy-Zuordnung.
ALIASES = {
    'Głęboki Skałki': 'Głębokie Skałki',
    'Pieczara Czasek': 'Pieczara Czaszek',
    'Kuźnia Worundiela': 'Kuźnia Worundriela',
    'Biblioteka Andarum': 'Świątynia Andarum - biblioteka',
    'Magazyn Świątyni': 'Świątynia Andarum - magazyn',
}


def icon_key(icon):
    # a/b sind Blickrichtungen/Farbvarianten derselben Grafikfamilie.
    return re.sub(r'[-_]?[ab](?=\.gif$)', '', icon)



def norm(s):
    s = unicodedata.normalize('NFKD', s.lower().replace('ł', 'l'))
    return ' '.join(''.join(c for c in s if not unicodedata.combining(c)).split())


class ForumParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.bold = self.under = 0
        self.line = []
        self.entries = []
        self.current = None
        self.stop = False

    def flush(self):
        text = ''.join(t for t, _, _ in self.line).strip()
        recommended = any(b and u for t, b, u in self.line if t.strip())
        self.line = []
        if text == 'INNE EXPOWISKA':
            self.stop = True
        m = re.fullmatch(r'(.+?)\s*\(~(\d+) lvl\)\s*[–-]\s*(.+)', text)
        if m and not self.stop:
            self.current = dict(name=m[1], level=int(m[2]), places=m[3], recommended=recommended, icons=[])
            self.entries.append(self.current)

    def handle_starttag(self, tag, attrs):
        if tag in ('br', 'blockquote', 'center'):
            self.flush()
        if tag == 'b': self.bold += 1
        if tag == 'u': self.under += 1
        if tag == 'img' and self.current and not self.stop:
            src = dict(attrs).get('src', '')
            if '/npc/' in src:
                icon = src.split('/npc/', 1)[1]
                if icon not in self.current['icons']: self.current['icons'].append(icon)

    def handle_endtag(self, tag):
        if tag in ('blockquote', 'center'): self.flush()
        if tag == 'b': self.bold = max(0, self.bold - 1)
        if tag == 'u': self.under = max(0, self.under - 1)

    def handle_data(self, text):
        self.line.append((text, self.bold, self.under))


def parse_html(text):
    p = ForumParser(); p.feed(text); p.flush()
    if not p.entries or any(not e['icons'] for e in p.entries):
        raise ValueError('Keine vollständige Expowisko-Liste mit Mob-Bildern erkannt')
    plain = re.sub(r'<[^>]+>', '', text)
    date = re.search(r'Ostatnia aktualizacja:\s*(\d{2})\.(\d{2})\.(\d{4})', plain)
    updated = '-'.join(reversed(date.groups())) if date else None
    return dict(source=URL, updated=updated, entries=p.entries)


def matching_maps(entry, world):
    """Kartennamen samt Etagen + durch Mob-Bilder belegte angrenzende Karten.

    Unspezifische Ortsangaben (z.B. nördlich Nithal) werden ausschließlich über
    die mitgelieferten Mob-Bilder abgeglichen, nicht durch erfundene Ortsnamen.
    """
    seeds, unresolved = set(), []
    for place in entry['places'].split(', '):
        base = re.split(r'\s+(?:w|we)\s+', place, maxsplit=1)[0]
        base = re.sub(r' z wnętrzami piramid$', '', base)
        key = norm(ALIASES.get(base, base))
        ids = {int(k) for k, m in world.items() if norm(m[2]) == key
               or norm(m[2]).startswith(key + ' p.') or norm(m[2]).startswith(key + ' - ')}
        if not ids: unresolved.append(place)
        seeds.update(ids)
    icons = {icon_key(x) for x in entry['icons']}
    targets = {int(k) for k, m in world.items() if sum(x[2] for x in m[4]
        if len(x) > 4 and icon_key(x[4]) in icons and not x[4].startswith(('e1/', 'e2/'))
        and abs(x[1] - entry['level']) <= 15) >= 3}
    # Benannte Gebiete begrenzen den Bildabgleich; bei rein beschreibenden Ortsangaben
    # ist die exakte Mob-Grafik die verbleibende belegbare Zuordnung.
    if not seeds:
        return targets, unresolved, 'icons'
    allowed = seeds | targets
    selected = set(seeds)
    q = deque(sorted(seeds))
    while q:
        k = q.popleft()
        for to, *_ in world[str(k)][3]:
            if to in allowed and to not in selected:
                selected.add(to); q.append(to)
    return selected, unresolved, 'names+icons'


def components(ids, world):
    doors = {k: {g[0] for g in world[str(k)][3]} for k in ids}
    adj = {k: sorted(t for t in doors[k] if t in ids and t != k and k in doors[t]) for k in ids}
    seen, out = set(), []
    for root in sorted(ids):
        if root in seen: continue
        walk, stack, members = [root], [(root, 0)], {root}
        seen.add(root)
        while stack:
            k, i = stack[-1]
            if i == len(adj[k]):
                stack.pop()
                if stack: walk.append(stack[-1][0])
            else:
                to = adj[k][i]; stack[-1] = (k, i + 1)
                if to not in seen:
                    seen.add(to); members.add(to); walk.append(to); stack.append((to, 0))
        if len(walk) > 1: walk.pop()
        out.append(dict(maps=walk, cards=len(members)))
    return out


def build(source, world):
    entries = []
    for i, e in enumerate(source['entries']):
        ids, unresolved, method = matching_maps(e, world)
        # Nur gewöhnliche passende Mobs für den Angriffsbereich, keine Elite-Ausreißer.
        icons = {icon_key(x) for x in e['icons']}
        levels = [m[1] for k in ids for m in world[str(k)][4]
                  if len(m) > 4 and icon_key(m[4]) in icons and not m[4].startswith(('e1/', 'e2/'))
                  and abs(m[1] - e['level']) <= 15]
        if not levels:
            levels = [m[1] for k in ids for m in world[str(k)][4] if len(m) > 4
                      and not m[4].startswith(('e1/', 'e2/')) and abs(m[1] - e['level']) <= 5]
        lv = [min(levels + [e['level']]), max(levels + [e['level']])] if levels else [max(1, e['level'] - 5), e['level'] + 5]
        entries.append(dict(id=i + 1, name=e['name'], level=e['level'], recommended=e['recommended'],
            places=e['places'], lv=lv, maps=sorted(ids), parts=components(ids, world),
            match=method, unresolved=unresolved))
    return dict(source=source['source'], updated=source['updated'], entries=entries)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--html', type=Path)
    ap.add_argument('--embed', action='store_true')
    args = ap.parse_args()
    if args.html:
        source = parse_html(args.html.read_text(encoding='utf-8'))
        SOURCE.write_text(json.dumps(source, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    else:
        source = json.loads(SOURCE.read_text(encoding='utf-8'))
    world = json.loads((ROOT / 'margobot_world.json').read_text(encoding='utf-8'))
    catalog = build(source, world)
    OUT.write_text(json.dumps(catalog, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    if args.embed:
        target = ROOT / 'margobot_auto.user.js'
        text = target.read_text(encoding='utf-8')
        compact = [{k: e[k] for k in ('id', 'name', 'level', 'recommended', 'lv', 'maps')} for e in catalog['entries']]
        block = BEGIN + '\n    const FORUM_EXPOWISKA = ' + json.dumps(compact, ensure_ascii=False, separators=(',', ':')) + ';\n' + END
        if BEGIN in text:
            start = text.index(BEGIN); end = text.index(END, start) + len(END)
            text = text[:start] + block + text[end:]
        else:
            text = text.replace('    // ── XP nach offizieller Formel', block + '\n\n    // ── XP nach offizieller Formel', 1)
        target.write_text(text, encoding='utf-8')
    print(f"{len(catalog['entries'])} Expowiska, {sum(len(e['maps']) for e in catalog['entries'])} Kartenzuordnungen")
    for e in catalog['entries']:
        print(f"{e['id']:3} {e['name']:30} ~{e['level']:3} | {len(e['maps']):2} Karten, {len(e['parts']):2} Teile | {e['match']} | " + ', '.join(e['unresolved']))


if __name__ == '__main__': main()
